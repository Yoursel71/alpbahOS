#!/usr/bin/env python3
"""LIVE-PROFILE-01: writes profiles/desktop/xdg/kdeglobals (installed as /etc/xdg/kdeglobals) from
profiles/desktop/colorscheme/alpbah-dark.colors.

Why: Plasma 6.7 applies the look-and-feel defaults (wallpaper, layout) but only writes the colour scheme NAME, so KDE
and Qt apps stayed light in the round 24 live session. The system-wide kdeglobals therefore carries the colour groups
of the scheme itself ([Colors:*], [ColorEffects:*], [WM]) next to LookAndFeelPackage, ColorScheme and the icon theme.
A user's own ~/.config/kdeglobals still wins (System Settings > Colours).
Usage: build_xdg_kdeglobals.py [--check]   (--check: exit 1 if the file differs from a fresh build)
"""
import configparser
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SCHEME = HERE.parent / "colorscheme" / "alpbah-dark.colors"
OUT = HERE.parent / "xdg" / "kdeglobals"

cp = configparser.ConfigParser(interpolation=None, strict=False)
cp.optionxform = str
cp.read(SCHEME, encoding="utf-8")
lines = ["# alpbahOS system-wide KDE defaults (/etc/xdg/kdeglobals). Generated by profiles/desktop/tools/build_xdg_kdeglobals.py",
         "# from profiles/desktop/colorscheme/alpbah-dark.colors; do not edit by hand. The user's ~/.config/kdeglobals wins.",
         "[KDE]", "LookAndFeelPackage=org.alpbahos.solid.desktop", f"contrast={cp['KDE'].get('contrast', '4')}", "",
         "[General]", "ColorScheme=alpbah-dark", "", "[Icons]", "Theme=breeze-dark", ""]
for sec in cp.sections():
    if sec.startswith(("Colors:", "ColorEffects:")) or sec == "WM":
        lines.append(f"[{sec}]")
        lines += [f"{k}={v}" for k, v in cp[sec].items()]
        lines.append("")
text = "\n".join(lines).rstrip("\n") + "\n"
if "--check" in sys.argv[1:]:
    sys.exit(0 if OUT.read_text(encoding="utf-8") == text else 1)
OUT.write_text(text, encoding="utf-8")
print(f"wrote {OUT} ({len(cp.sections())} scheme groups read)")
