#!/usr/bin/env python3
"""PLYMOUTH-01 (review item D2): builds the alpbahOS Plymouth theme (script plugin) into branding/plymouth-theme/alpbahos/.

Host tool (Python 3 + Pillow). Layout from the master task D2: background #0b1014; centred column: mark 236 px wide,
24 px gap, wordmark 56 px (Inter Bold, "alpbah" #f4f8fb, "OS" #00aeef, D155), 48 px gap, progress bar 280x4
(track #1d2c38, fill #00aeef, 2 px radius) that follows boot progress; bottom centre, 56 px from the edge,
"Başlatılıyor" (boot) / "Kapatılıyor" (shutdown) / "Yeniden başlatılıyor" (reboot) in JetBrains Mono 14 px #8ea2af.
Text is rendered into PNGs here (exact pixel sizes, no font lookup at boot); only the LUKS prompt uses Plymouth's
own text rendering (Image.Text), so the theme never blocks a passphrase prompt.
The mark comes from docs/assets/alpbahOS-logo.png (296x359) through scripts/rebuild/r9/brand-logo-r9.py (keyed, native
size), rows above the wordmark, trimmed, scaled down to 236 px wide (never enlarged).
Usage: build_plymouth_theme.py --inter-dir DIR --jbm-dir DIR
"""
import argparse
import hashlib
import os
import subprocess
import tempfile
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(HERE, "..", "alpbahos")
SRC_LOGO = os.path.join(REPO, "docs/assets/alpbahOS-logo.png")
STRONG, CYAN, TRACK, MUTED = (244, 248, 251), (0, 174, 239), (29, 44, 56), (142, 162, 175)
MARK_W, WORD_PX, BAR_W, BAR_H, LABEL_PX = 236, 56, 280, 4, 14


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def text_png(path, parts, font, pad=2):
    """parts: [(text, rgb)], drawn left to right on transparency, tight height from the font metrics."""
    asc, desc = font.getmetrics()
    w = round(sum(font.getlength(t) for t, _ in parts)) + 2 * pad
    im = Image.new("RGBA", (w, asc + desc + 2 * pad), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    x = pad
    for t, c in parts:
        d.text((x, pad), t, font=font, fill=c + (255,))
        x += font.getlength(t)
    im.save(path, optimize=True)


def bar_png(path, colour):
    s = 8
    big = Image.new("RGBA", (BAR_W * s, BAR_H * s), (0, 0, 0, 0))
    ImageDraw.Draw(big).rounded_rectangle([0, 0, BAR_W * s - 1, BAR_H * s - 1], radius=2 * s, fill=colour + (255,))
    big.resize((BAR_W, BAR_H), Image.LANCZOS).save(path, optimize=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inter-dir", required=True)
    ap.add_argument("--jbm-dir", required=True)
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    with tempfile.TemporaryDirectory() as td:
        keyed = os.path.join(td, "logo.png")
        src_h = Image.open(SRC_LOGO).height
        subprocess.run(["python3", "-B", os.path.join(REPO, "scripts/rebuild/r9/brand-logo-r9.py"), SRC_LOGO,
                        "--png", keyed, "--height", str(src_h)], check=True, stdout=subprocess.DEVNULL)
        logo = Image.open(keyed).convert("RGBA")
    alpha = logo.getchannel("A")
    rows = [y for y in range(logo.height) if alpha.crop((0, y, logo.width, y + 1)).getextrema()[1] > 8]
    cut = next(rows[i] for i in range(1, len(rows)) if rows[i] - rows[i - 1] > 1)
    mark = logo.crop((0, 0, logo.width, cut))
    mark = mark.crop(mark.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox())
    native = mark.size
    if mark.width > MARK_W:
        mark = mark.resize((MARK_W, round(mark.height * MARK_W / mark.width)), Image.LANCZOS)
    mark.save(os.path.join(OUT, "mark.png"), optimize=True)

    inter_bold = ImageFont.truetype(os.path.join(a.inter_dir, "Inter-Bold.ttf"), WORD_PX)
    text_png(os.path.join(OUT, "wordmark.png"), [("alpbah", STRONG), ("OS", CYAN)], inter_bold)
    jbm = ImageFont.truetype(os.path.join(a.jbm_dir, "JetBrainsMono-Regular.ttf"), LABEL_PX)
    for name, text in [("boot", "Başlatılıyor"), ("shutdown", "Kapatılıyor"), ("reboot", "Yeniden başlatılıyor")]:
        text_png(os.path.join(OUT, f"label-{name}.png"), [(text, MUTED)], jbm)
    bar_png(os.path.join(OUT, "track.png"), TRACK)
    bar_png(os.path.join(OUT, "fill.png"), CYAN)

    open(os.path.join(OUT, "alpbahos.plymouth"), "w").write(
        "[Plymouth Theme]\nName=alpbahOS\n"
        "Description=alpbahOS boot splash: mark, wordmark and a progress bar (PLYMOUTH-01)\nModuleName=script\n\n"
        "[script]\nImageDir=/usr/share/plymouth/themes/alpbahos\n"
        "ScriptFile=/usr/share/plymouth/themes/alpbahos/alpbahos.script\n")
    manifest = ["# PLYMOUTH-01: generated by branding/plymouth-theme/tools/build_plymouth_theme.py; do not edit by hand.",
                f"# mark from docs/assets/alpbahOS-logo.png sha256={sha(SRC_LOGO)} via brand-logo-r9.py (native height),"
                f" rows 0..{cut - 1}, bbox {native[0]}x{native[1]}, scaled to {mark.width}x{mark.height}",
                "# fonts: Inter-Bold.ttf (Inter 4.1), JetBrainsMono-Regular.ttf (2.304); see branding/grub-theme MANIFEST"]
    for fn in sorted(os.listdir(OUT)):
        if fn != "MANIFEST.txt":
            manifest.append(f"{sha(os.path.join(OUT, fn))}  {fn}")
    open(os.path.join(OUT, "MANIFEST.txt"), "w").write("\n".join(manifest) + "\n")
    print(f"mark {mark.width}x{mark.height} (native {native[0]}x{native[1]})")


if __name__ == "__main__":
    main()
